// Run against an explicitly provisioned local demo DB; creates fictional jobs.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require(path.resolve(process.argv[2]));
const base = process.argv[3] || "http://127.0.0.1:18041";
assert(["127.0.0.1", "localhost"].includes(new URL(base).hostname), "Local demo only");
const artifactDir = path.resolve("car mechanic assistant/runtime/workshop-browser-tests");
fs.mkdirSync(artifactDir, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(base + "/workshop");
    await page.locator("#source-file").setInputFiles("tests/fixtures/workshop/synthetic-sheet.png");
    await page.locator("#attach-source").click();
    await page.waitForFunction(() => document.getElementById("source-identity").textContent.startsWith("Source ID:"));
    await page.locator("#job_reference").fill("DEMO-BROWSER-" + Date.now());
    await page.locator("#job_reference-state").selectOption("confirmed");
    await page.locator("#record-stage").selectOption("quote");
    await page.locator("#currency").fill("SGD");
    await page.locator("#currency-state").selectOption("confirmed");
    await page.locator("#add-item").click();
    const item = page.locator("#items .item").first();
    await item.getByLabel("Literal item description", { exact: true }).fill("示例 / Example inspect door");
    await item.getByLabel("Clarified description", { exact: true }).fill("Fictional door inspection / 示例");
    await item.getByLabel("Description review state", { exact: true }).selectOption("confirmed");
    const amount = item.getByLabel("Parsed amount (empty means unknown)", { exact: true });
    await amount.fill("abc");
    await page.locator("#save-draft").click();
    await page.waitForFunction(() => document.getElementById("status").classList.contains("error"));
    assert.equal(await amount.inputValue(), "abc", "Invalid value must remain editable");
    await amount.fill("25.10");
    await item.getByLabel("Amount review state", { exact: true }).selectOption("confirmed");
    const createdPromise = page.waitForResponse(response => response.url() === base + "/api/v1/workshop/jobs" && response.status() === 201);
    await page.locator("#save-draft").click();
    const job = await (await createdPromise).json();
    await page.waitForFunction(id => document.getElementById("record-identity").textContent.includes(id), job.id);
    assert.equal(job.draft.items[0].amount, "25.10");
    await page.reload();
    await page.waitForFunction(id => document.getElementById("record-identity").textContent.includes(id), job.id);
    assert.equal(await page.locator("#items .item").getByLabel("Clarified description", { exact: true }).inputValue(), "Fictional door inspection / 示例");
    await page.waitForFunction(() => document.getElementById("source-image").naturalWidth > 0);
    await page.locator("#zoom-in").click();
    assert.equal(await page.locator("#zoom-label").textContent(), "125%");
    await page.locator("#rotate-source").click();
    assert((await page.locator("#source-image").getAttribute("style")).includes("90deg"));
    const preview = await context.request.get(base + "/api/v1/workshop/documents/" + job.draft.source_document_id + "/preview");
    assert.deepEqual(await preview.body(), fs.readFileSync("tests/fixtures/workshop/synthetic-sheet.png"));
    await page.locator("#job_reference").focus();
    await page.keyboard.press("Tab");
    assert.equal(await page.evaluate(() => document.activeElement.id), "job_reference-state");
    await page.screenshot({ path: path.join(artifactDir, "manual-desktop.png"), fullPage: true });

    const untrustedNote = '</textarea><img src=x onerror="window.workshopXss=true">';
    const changed = await context.request.patch(base + "/api/v1/workshop/jobs/" + job.id, { data: { expected_version: 1, draft: { ...job.draft, diagram_notes_raw: untrustedNote } } });
    assert.equal(changed.status(), 200);
    await page.locator("#optional-details summary").click();
    await page.locator("#diagram_notes_raw").fill("MUST RETAIN UNSAVED / 示例");
    await page.locator("#save-draft").click();
    await page.waitForFunction(() => document.getElementById("status").textContent.includes("Draft changed"));
    assert.equal(await page.locator("#diagram_notes_raw").inputValue(), "MUST RETAIN UNSAVED / 示例");
    assert.equal(await page.locator("#dirty-label").textContent(), "Unsaved changes");
    await page.route(base + "/api/v1/workshop/jobs/" + job.id, route => route.fulfill({ status: 503, json: { detail: "Fictional test failure" } }));
    await page.locator("#save-draft").click();
    await page.waitForFunction(() => document.getElementById("status").textContent.includes("Fictional test failure"));
    assert.equal(await page.locator("#diagram_notes_raw").inputValue(), "MUST RETAIN UNSAVED / 示例");
    await page.unroute(base + "/api/v1/workshop/jobs/" + job.id);
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), "Mobile page must not overflow horizontally");
    await page.screenshot({ path: path.join(artifactDir, "manual-mobile.png"), fullPage: true });
    const reopened = await context.newPage();
    await reopened.goto(base + "/workshop?job=" + job.id);
    await reopened.waitForFunction(id => document.getElementById("record-identity").textContent.includes(id), job.id);
    await reopened.locator("#optional-details summary").click();
    assert.equal(await reopened.locator("#diagram_notes_raw").inputValue(), untrustedNote);
    assert.equal(await reopened.evaluate(() => window.workshopXss), undefined);
    await reopened.locator("#confirm-record").click();
    assert((await reopened.locator("#status").textContent()).includes("Enter your reviewer name"));
    await reopened.locator("#reviewer").fill("Fictional browser reviewer");
    await reopened.locator("#review-ack").check();
    const reviewPromise = reopened.waitForResponse(response => response.url().endsWith("/confirm") && response.status() === 200);
    await reopened.locator("#confirm-record").click();
    const firstReview = await (await reviewPromise).json();
    assert.equal(firstReview.version, 2); assert.equal(firstReview.record.record_stage, "quote");
    await reopened.waitForFunction(() => document.getElementById("review-state").textContent.includes("has been reviewed"));
    const correctedItem = reopened.locator("#items .item").first();
    await correctedItem.getByLabel("Clarified description", { exact: true }).fill("Fictional corrected inspection / 示例");
    assert.equal(await correctedItem.getByLabel("Description review state", { exact: true }).inputValue(), "proposed");
    assert(await reopened.locator("#confirm-record").isDisabled());
    await reopened.locator("#save-draft").click();
    await reopened.waitForFunction(() => document.getElementById("record-identity").textContent.includes("version 3"));
    await reopened.locator("#review-ack").check();
    await reopened.locator("#confirm-record").click();
    await reopened.waitForFunction(() => document.getElementById("status").textContent.includes("confirmed active item descriptions"));
    await reopened.locator("#items .item").getByLabel("Description review state", { exact: true }).selectOption("confirmed");
    await reopened.locator("#date_note_raw").fill("Fictional long literal note\n".repeat(100));
    await reopened.locator("#save-draft").click();
    await reopened.waitForFunction(() => document.getElementById("record-identity").textContent.includes("version 4"));
    await reopened.locator("#review-ack").check();
    await reopened.locator("#confirm-record").scrollIntoViewIfNeeded();
    const confirmBox = await reopened.locator("#confirm-record").boundingBox();
    assert(confirmBox.y >= 0 && confirmBox.y + confirmBox.height <= 1000, "Long notes must not hide confirmation");
    await reopened.locator("#confirm-record").click();
    await reopened.waitForFunction(() => document.getElementById("review-state").textContent.includes("has been reviewed"));
    const revisions = await (await context.request.get(base + "/api/v1/workshop/jobs/" + job.id + "/revisions")).json();
    assert.deepEqual(revisions.map(revision => revision.version), [4, 2]);
    assert.equal(revisions[1].record.items[0].description, firstReview.record.items[0].description);
    assert.equal(revisions[0].record.items[0].description, "Fictional corrected inspection / 示例");
    await reopened.locator("#review-ack").check();
    await reopened.locator("#confirm-record").click();
    await reopened.waitForFunction(() => document.getElementById("status").textContent.includes("Saved reviewed version 4"));
    assert.deepEqual(await (await context.request.get(base + "/api/v1/workshop/jobs/" + job.id + "/revisions")).json(), revisions);
    const currentDetails = reopened.locator("#reviewed-history details").first();
    await currentDetails.locator("summary").click();
    const downloadPromise = reopened.waitForEvent("download");
    const exportPromise = reopened.waitForResponse(response => response.url().endsWith("/exports") && response.request().method() === "POST" && response.status() === 200);
    await currentDetails.getByRole("button", { name: "Download demo CSV · version 4", exact: true }).click();
    const exported = await (await exportPromise).json();
    const download = await downloadPromise;
    assert.equal(download.suggestedFilename(), `workshop-demo-${job.id}-v4.csv`);
    const outputPath = path.join(artifactDir, "fictional-reviewed-v4.csv");
    await download.saveAs(outputPath);
    const content = fs.readFileSync(outputPath);
    assert.equal(require("node:crypto").createHash("sha256").update(content).digest("hex"), exported.checksum);
    assert(content.toString("utf8").includes("Fictional corrected inspection / 示例"));
    assert(content.toString("utf8").includes("DEMO_ONLY"));
    const repeatedExport = await context.request.post(base + "/api/v1/workshop/revisions/" + revisions[0].id + "/exports");
    assert.deepEqual(await repeatedExport.json(), exported);
    const oldExport = await (await context.request.post(base + "/api/v1/workshop/revisions/" + revisions[1].id + "/exports")).json();
    assert.notEqual(oldExport.id, exported.id);
    const oldCsv = await (await context.request.get(base + "/api/v1/workshop/exports/" + oldExport.id + "/download")).text();
    assert(oldCsv.includes("Fictional door inspection / 示例") && !oldCsv.includes("Fictional corrected inspection / 示例"));
    const afterExport = await context.newPage();
    await afterExport.goto(base + "/workshop?job=" + job.id);
    await afterExport.waitForFunction(() => document.getElementById("review-state").textContent.includes("has been reviewed"));
    assert.equal(await afterExport.locator("#reviewed-history details").count(), 2);
    await reopened.screenshot({ path: path.join(artifactDir, "reviewed-history.png"), fullPage: true });
    assert.deepEqual(errors, []);
    console.log("Browser checks passed: manual capture/failure handling, safe source view, mobile/keyboard/untrusted text, review/correction/history, versioned CSV download/checksum/repeat and reopen after output.");
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
